"""sources.lock: which source files were ingested, their content hash, and the notes they produced.

    python pipeline/lock.py status <file-or-folder>...      # new / changed / unchanged / skipped
    python pipeline/lock.py record <file> --notes <note>... [--attachments <file>...]

Entries are keyed by file name, not path: the originals live in the course's own storage (D-006).
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import sys
from pathlib import Path

import yaml

import notes

LOCK = notes.REPO / "sources.lock"
FORMATS = (".docx", ".pdf", ".pptx")
HEADER = "# Generated by pipeline/lock.py. Source originals are not in the repo (D-006).\n"


def load(path: Path = LOCK) -> dict:
    if not path.exists():
        return {}
    return (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("sources") or {}


def save(entries: dict, path: Path = LOCK) -> None:
    data = {"sources": dict(sorted(entries.items()))}
    text = HEADER + yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=10_000)
    path.write_text(text, encoding="utf-8", newline="\n")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def collect(paths: list[Path], work: Path = notes.WORK) -> tuple[list[Path], list[tuple[Path, str]]]:
    """Expand folders and pick the files to ingest. A PDF is replaced by the DOCX with the
    same name when one sits next to it (D-005). Raw extractions under `work` are ignored.
    Returns (files, [(skipped file, reason)])."""
    work = work.resolve()
    found: list[Path] = []
    skipped: list[tuple[Path, str]] = []
    for p in paths:
        if p.is_dir():
            found += sorted(f for f in p.rglob("*") if f.is_file() and not f.resolve().is_relative_to(work))
        elif p.is_file():
            found.append(p)
        else:
            skipped.append((p, "not found"))
    files: list[Path] = []
    for f in found:
        if f.name.startswith("~$"):  # Office lock files
            continue
        if f.suffix.lower() not in FORMATS:
            skipped.append((f, f"unsupported format {f.suffix or '(none)'}"))
            continue
        if f.suffix.lower() == ".pdf":
            docx = next((d for d in (f.with_suffix(".docx"), f.with_suffix(".DOCX")) if d.is_file()), None)
            if docx is not None:
                skipped.append((f, f"{docx.name} is used instead"))
                f = docx
        if f not in files:
            files.append(f)
    return files, skipped


def status(files: list[Path], entries: dict) -> list[tuple[Path, str]]:
    result = []
    for f in files:
        entry = entries.get(f.name)
        if entry is None:
            result.append((f, "new"))
        elif entry.get("sha256") != sha256(f):
            result.append((f, "changed"))
        else:
            result.append((f, "unchanged"))
    return result


def record(entries: dict, source: Path, note_paths: list[str], attachments: list[str], today: str) -> dict:
    # Always "/": paths typed or tab-completed on Windows come with "\".
    note_paths = [n.replace("\\", "/") for n in note_paths]
    entry = {"sha256": sha256(source), "ingested": today, "notes": sorted(note_paths)}
    if attachments:
        entry["attachments"] = sorted(attachments)
    return {**entries, source.name: entry}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lock", type=Path, default=LOCK, help=argparse.SUPPRESS)
    sub = parser.add_subparsers(dest="command", required=True)
    st = sub.add_parser("status", help="classify source files against the lock")
    st.add_argument("paths", nargs="+", type=Path)
    rec = sub.add_parser("record", help="record a source file after its notes are written")
    rec.add_argument("source", type=Path)
    rec.add_argument("--notes", nargs="+", required=True, help="note paths relative to content/")
    rec.add_argument("--attachments", nargs="*", default=[], help="attachment file names")
    args = parser.parse_args(argv)

    entries = load(args.lock)
    if args.command == "status":
        files, skipped = collect(args.paths)
        for f, state in status(files, entries):
            print(f"{state:<10} {f}")
        for f, reason in skipped:
            print(f"{'skipped':<10} {f} ({reason})")
        return 0

    if not args.source.is_file():
        print(f"source file not found: {args.source}", file=sys.stderr)
        return 2
    missing = [n for n in args.notes if not (notes.CONTENT / n.replace("\\", "/")).exists()]
    if missing:
        print("these notes don't exist under content/:", *missing, sep="\n  ", file=sys.stderr)
        return 2
    today = datetime.date.today().isoformat()
    save(record(entries, args.source, args.notes, args.attachments, today), args.lock)
    print(f"recorded {args.source.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
